const ACTION_IDS = new Map(
  ANIMATION_ACTIONS.map((name, index) => [name, index]),
);
if (ACTION_IDS.size !== ANIMATION_ACTIONS.length) {
  throw new Error("Duplicate animation action name");
}
export function animationId(name) {
  const id = ACTION_IDS.get(name);
  if (id === undefined) {
    throw new Error(`Unsupported animation action: ${String(name)}`);
  }
  return id;
}
export function animationName(id) {
  if (
    !Number.isInteger(id) ||
    Object.is(id, -0) ||
    id < 0 ||
    id >= ANIMATION_ACTIONS.length
  ) {
    throw new Error("Unsupported animation action ID");
  }
  return ANIMATION_ACTIONS[id];
}
